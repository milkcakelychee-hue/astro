import { beforeAll, expect, it } from 'vitest'
import { retroCycles } from '../src/engine/retro.ts'
import { dateOfJd, thaiParts } from '../src/engine/sky.ts'
import { getSwe } from './helpers.ts'
import type { Swe } from '../src/engine/swe.ts'

let swe: Swe
beforeAll(async () => { swe = await getSwe() })
const L = [
  ['m', '2026-10-04', '2026-10-24', '2026-11-13', '2026-11-30'], ['V', '2026-08-31', '2026-10-03', '2026-11-14', '2026-12-16'],
  ['s', '2026-04-20', '2026-07-27', '2026-12-11', '2027-03-15'], ['N', '2026-03-16', '2026-07-07', '2026-12-13', '2027-04-03'],
  ['U', '2026-05-25', '2026-09-11', '2027-02-08', '2027-05-26'], ['P', '2026-01-12', '2026-05-06', '2026-10-16', '2027-02-07'],
  ['J', '2026-09-17', '2026-12-13', '2027-04-13', '2027-07-11'], ['a', '2026-11-05', '2027-01-10', '2027-04-01', '2027-06-08'],
  ['m', '2027-01-26', '2027-02-10', '2027-03-03', '2027-03-24'], ['m', '2027-05-26', '2027-06-11', '2027-07-05', '2027-07-19'],
  ['m', '2027-09-17', '2027-10-07', '2027-10-28', '2027-11-13'], ['s', '2027-05-05', '2027-08-10', '2027-12-24', '2028-03-27'],
  ['N', '2027-03-19', '2027-07-10', '2027-12-15', '2028-04-04'], ['U', '2027-05-30', '2027-09-15', '2028-02-13', '2028-05-30'],
  ['P', '2027-01-14', '2027-05-08', '2027-10-18', '2028-02-09'],
]
const f = (jd: number) => { const p = thaiParts(dateOfJd(jd)); return `${p.y}-${String(p.mo).padStart(2, '0')}-${String(p.d).padStart(2, '0')}` }
it('ตรงกับดีไซน์', () => {
  const cy = retroCycles(swe, swe.julday(2026, 11, 1, 0), swe.julday(2028, 1, 1, 0))
  // จุดหยุด R/D ต้องตรงวัน · เงาก่อน/หลังยอม ±1 วัน (ดีไซน์ต่าง 1 วันในรอบที่ข้ามองศาตอนค่ำ — ดู docs/09)
  for (const [p, pre, r, d, post] of L) {
    const c = cy.find((x) => x.p === p && f(x.r) === r)
    expect(c, `${p} ${r}`).toBeTruthy()
    expect(f(c!.d)).toBe(d)
    for (const [jd, e] of [[c!.pre, pre], [c!.post, post]] as const) expect(Math.abs(jd + 7 / 24 - (Date.parse(e!) / 864e5 + 2440587.5 + 0.5))).toBeLessThan(2)
  }
}, 120000)
